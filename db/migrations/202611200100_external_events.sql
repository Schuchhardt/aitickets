-- Eventos externos: eventos de otras ticketeras (o sin ticketera) que se registran desde el MCP de administración para
-- mapear el mercado (qué eventos hay, de qué categoría y nicho, quién los produce, dónde, si usan ticketera y cuál) y
-- alimentar el modelo de fechas (evaluate_event_date / recommend_event_dates). No se muestran en ninguna parte de la
-- plataforma: solo los leen y escriben las herramientas de admin (src/lib/admin-api/tools/market.ts).
-- Spec: docs/specs/eventos-externos.md.
--
--   productora (aitickets_external_producers) 1 ── n evento (aitickets_external_events) 1 ── n función (…_event_dates) n ── 1 lugar (…_venues)
--
-- Un evento puede tener varias funciones (temporada) y cada función su propio lugar y ciudad (gira).
-- Idempotente. Solo toca objetos de AI Tickets.

-- ---------------------------------------------------------------------------
-- Productoras
-- ---------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS public.aitickets_external_producers (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name text NOT NULL,
  -- ig:<handle> si se conoce su Instagram, si no name:<nombre normalizado>: evita duplicar la misma productora
  producer_key text NOT NULL,
  instagram text,
  website text,
  city text,
  city_key text,
  region text,
  -- Si ya es productor de AI Tickets o un lead del pipeline de ventas
  organization_id bigint REFERENCES public.organizations(id) ON DELETE SET NULL,
  lead_id uuid REFERENCES public.aitickets_leads(id) ON DELETE SET NULL,
  notes text,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT aitickets_external_producers_producer_key_key UNIQUE (producer_key)
);
CREATE INDEX IF NOT EXISTS aitickets_external_producers_organization_idx ON public.aitickets_external_producers (organization_id) WHERE organization_id IS NOT NULL;
CREATE INDEX IF NOT EXISTS aitickets_external_producers_lead_idx ON public.aitickets_external_producers (lead_id) WHERE lead_id IS NOT NULL;

ALTER TABLE public.aitickets_external_producers ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON TABLE public.aitickets_external_producers FROM PUBLIC, anon, authenticated;
REVOKE ALL ON SEQUENCE public.aitickets_external_producers_id_seq FROM PUBLIC, anon, authenticated;
GRANT USAGE, SELECT ON SEQUENCE public.aitickets_external_producers_id_seq TO service_role;

-- ---------------------------------------------------------------------------
-- Lugares (recintos)
-- ---------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS public.aitickets_external_venues (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name text NOT NULL,
  -- nombre normalizado | ciudad normalizada
  venue_key text NOT NULL,
  address text,
  commune text,
  city text,
  -- Ciudad normalizada (las comunas del Gran Santiago son "santiago"; Viña y Valparaíso "gran_valparaiso"…)
  city_key text,
  region text,
  capacity integer,
  notes text,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT aitickets_external_venues_venue_key_key UNIQUE (venue_key),
  CONSTRAINT aitickets_external_venues_capacity_check CHECK (capacity IS NULL OR capacity > 0)
);
CREATE INDEX IF NOT EXISTS aitickets_external_venues_city_idx ON public.aitickets_external_venues (city_key);

ALTER TABLE public.aitickets_external_venues ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON TABLE public.aitickets_external_venues FROM PUBLIC, anon, authenticated;
REVOKE ALL ON SEQUENCE public.aitickets_external_venues_id_seq FROM PUBLIC, anon, authenticated;
GRANT USAGE, SELECT ON SEQUENCE public.aitickets_external_venues_id_seq TO service_role;

-- ---------------------------------------------------------------------------
-- Eventos (el espectáculo: una temporada o una gira es UN evento con varias funciones)
-- ---------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS public.aitickets_external_events (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name text NOT NULL,
  -- Nombre normalizado: encuentra el mismo evento registrado desde otra fuente
  name_key text NOT NULL,
  -- Categoría (taxonomía en código, src/lib/market/taxonomy.ts): concierto, festival, fiesta, club, stand_up, teatro, …
  category text NOT NULL,
  -- Nicho dentro de la categoría, normalizado: techno, reggaeton, impro, jazz, tecnologia, …
  niche text,
  tags text[] NOT NULL DEFAULT '{}',
  producer_id bigint REFERENCES public.aitickets_external_producers(id) ON DELETE SET NULL,
  -- Slug de la ticketera (passline, puntoticket, ticketmaster…); 'none' = sin ticketera; NULL = no se sabe
  ticketing_platform text,
  ticketing_url text,
  price_min integer,
  price_max integer,
  is_free boolean,
  -- Cuándo se anunció / salió a la venta (corrige la competencia de fechas lejanas, aún sin anunciar)
  announced_at timestamptz,
  source text NOT NULL DEFAULT 'manual',
  source_url text,
  external_id text,
  notes text,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT aitickets_external_events_prices_check CHECK (
    (price_min IS NULL OR price_min >= 0) AND (price_max IS NULL OR price_max >= 0)
    AND (price_min IS NULL OR price_max IS NULL OR price_min <= price_max)
  )
);
CREATE UNIQUE INDEX IF NOT EXISTS aitickets_external_events_source_external_id_key
  ON public.aitickets_external_events (source, external_id) WHERE external_id IS NOT NULL;
CREATE INDEX IF NOT EXISTS aitickets_external_events_name_key_idx ON public.aitickets_external_events (name_key);
CREATE INDEX IF NOT EXISTS aitickets_external_events_category_idx ON public.aitickets_external_events (category, niche);
CREATE INDEX IF NOT EXISTS aitickets_external_events_producer_idx ON public.aitickets_external_events (producer_id);

ALTER TABLE public.aitickets_external_events ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON TABLE public.aitickets_external_events FROM PUBLIC, anon, authenticated;
REVOKE ALL ON SEQUENCE public.aitickets_external_events_id_seq FROM PUBLIC, anon, authenticated;
GRANT USAGE, SELECT ON SEQUENCE public.aitickets_external_events_id_seq TO service_role;

-- ---------------------------------------------------------------------------
-- Funciones (fechas): cada una con su día, hora, lugar y ciudad (gira) y su resultado
-- ---------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS public.aitickets_external_event_dates (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  event_id bigint NOT NULL REFERENCES public.aitickets_external_events(id) ON DELETE CASCADE,
  -- Día (hora de Chile) en que empieza y hora local; end_date para funciones de varios días (festival)
  event_date date NOT NULL,
  start_time time without time zone,
  end_date date,
  venue_id bigint REFERENCES public.aitickets_external_venues(id) ON DELETE SET NULL,
  -- Ciudad de la función (copiada del lugar, o indicada si no se conoce el lugar)
  city text,
  city_key text,
  commune text,
  region text,
  -- Capacidad de esta función (si no viene, la del lugar)
  capacity integer,
  status text NOT NULL DEFAULT 'scheduled',
  -- Resultado observado (entrena el modelo): agotada, cuándo, % vendido estimado y asistencia
  sold_out boolean,
  sold_out_at timestamptz,
  sold_pct numeric(5, 2),
  attendance integer,
  ticketing_url text,
  -- día | hora | lugar o ciudad: una función no se registra dos veces
  slot_key text NOT NULL,
  notes text,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT aitickets_external_event_dates_slot_key UNIQUE (event_id, slot_key),
  CONSTRAINT aitickets_external_event_dates_status_check CHECK (status IN ('scheduled', 'postponed', 'cancelled', 'completed')),
  CONSTRAINT aitickets_external_event_dates_end_date_check CHECK (end_date IS NULL OR end_date >= event_date),
  CONSTRAINT aitickets_external_event_dates_capacity_check CHECK (capacity IS NULL OR capacity > 0),
  CONSTRAINT aitickets_external_event_dates_sold_pct_check CHECK (sold_pct IS NULL OR (sold_pct >= 0 AND sold_pct <= 100)),
  CONSTRAINT aitickets_external_event_dates_attendance_check CHECK (attendance IS NULL OR attendance >= 0)
);
CREATE INDEX IF NOT EXISTS aitickets_external_event_dates_date_idx ON public.aitickets_external_event_dates (event_date);
CREATE INDEX IF NOT EXISTS aitickets_external_event_dates_city_date_idx ON public.aitickets_external_event_dates (city_key, event_date);
CREATE INDEX IF NOT EXISTS aitickets_external_event_dates_venue_idx ON public.aitickets_external_event_dates (venue_id) WHERE venue_id IS NOT NULL;

ALTER TABLE public.aitickets_external_event_dates ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON TABLE public.aitickets_external_event_dates FROM PUBLIC, anon, authenticated;
REVOKE ALL ON SEQUENCE public.aitickets_external_event_dates_id_seq FROM PUBLIC, anon, authenticated;
GRANT USAGE, SELECT ON SEQUENCE public.aitickets_external_event_dates_id_seq TO service_role;

-- ---------------------------------------------------------------------------
-- Calendario de mercado: fechas especiales que el modelo no puede calcular solo (interferiados, feriados regionales,
-- vacaciones escolares, elecciones, mega eventos, temporadas altas o bajas). Los feriados nacionales los calcula el
-- código (src/lib/market/calendar.ts); kind = 'no_holiday' anula uno calculado.
-- ---------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS public.aitickets_market_calendar (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  kind text NOT NULL,
  label text NOT NULL,
  date_from date NOT NULL,
  date_to date NOT NULL,
  -- Alcance: NULL = todo Chile / todas las ciudades / todas las categorías
  region text,
  city_key text,
  categories text[],
  -- Multiplicador sobre la nota de la fecha (0.1 a 2). NULL = el de su tipo (kind)
  impact numeric(4, 2),
  notes text,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT aitickets_market_calendar_kind_check CHECK (
    kind IN ('holiday', 'bridge_holiday', 'no_holiday', 'school_vacation', 'election', 'mega_event', 'high_demand', 'low_demand', 'blackout', 'other')
  ),
  CONSTRAINT aitickets_market_calendar_dates_check CHECK (date_to >= date_from),
  CONSTRAINT aitickets_market_calendar_impact_check CHECK (impact IS NULL OR (impact >= 0.1 AND impact <= 2))
);

CREATE INDEX IF NOT EXISTS aitickets_market_calendar_dates_idx ON public.aitickets_market_calendar (date_from, date_to);

ALTER TABLE public.aitickets_market_calendar ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON TABLE public.aitickets_market_calendar FROM PUBLIC, anon, authenticated;
REVOKE ALL ON SEQUENCE public.aitickets_market_calendar_id_seq FROM PUBLIC, anon, authenticated;
GRANT USAGE, SELECT ON SEQUENCE public.aitickets_market_calendar_id_seq TO service_role;
