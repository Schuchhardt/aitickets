-- Eventos externos: eventos de otras ticketeras (o sin ticketera) que se registran a mano o por agente desde el MCP de
-- administración para mapear el mercado (qué eventos hay, de qué tipo, si usan ticketera y cuál) y alimentar el modelo
-- de fechas (evaluate_event_date / recommend_event_dates). No se muestran en ninguna parte de la plataforma: solo los
-- leen y escriben las herramientas de admin (src/lib/admin-api/tools/market.ts). Spec: docs/specs/eventos-externos.md.
-- Idempotente. Solo toca objetos de AI Tickets.

CREATE TABLE IF NOT EXISTS public.aitickets_external_events (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name text NOT NULL,
  -- Taxonomía en código (src/lib/market/taxonomy.ts): concierto, festival, fiesta, club, stand_up, teatro, …
  event_type text NOT NULL,
  genre text,
  tags text[] NOT NULL DEFAULT '{}',
  -- Día (hora de Chile) en que empieza la función y hora local; end_date para eventos de varios días
  event_date date NOT NULL,
  start_time time without time zone,
  end_date date,
  city text,
  -- Ciudad normalizada para agrupar (las comunas del Gran Santiago son "santiago", Viña/Valparaíso "gran_valparaiso"…)
  city_key text,
  commune text,
  region text,
  country character(2) NOT NULL DEFAULT 'CL',
  venue_name text,
  capacity integer,
  organizer_name text,
  -- Organizador normalizado (handle de Instagram o nombre) para agrupar sus eventos
  organizer_key text,
  organizer_instagram text,
  organizer_website text,
  -- Slug de la ticketera (passline, puntoticket, ticketmaster…); 'none' = sin ticketera; NULL = no se sabe
  ticketing_platform text,
  ticketing_url text,
  price_min integer,
  price_max integer,
  is_free boolean,
  status text NOT NULL DEFAULT 'scheduled',
  -- Resultado observado (para el modelo): agotado, cuándo se agotó, % vendido estimado y asistencia
  sold_out boolean,
  sold_out_at timestamptz,
  sold_pct numeric(5, 2),
  attendance integer,
  -- Cuándo se anunció / salió a la venta (corrige la competencia de fechas lejanas, aún sin anunciar)
  announced_at timestamptz,
  source text NOT NULL DEFAULT 'manual',
  source_url text,
  external_id text,
  -- Agrupa las funciones de un mismo espectáculo (una temporada de teatro, una gira)
  series_key text,
  -- nombre normalizado | fecha | ciudad: evita registrar dos veces el mismo evento desde fuentes distintas
  dedupe_key text NOT NULL,
  organization_id bigint REFERENCES public.organizations(id) ON DELETE SET NULL,
  lead_id uuid REFERENCES public.aitickets_leads(id) ON DELETE SET NULL,
  notes text,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT aitickets_external_events_dedupe_key_key UNIQUE (dedupe_key),
  CONSTRAINT aitickets_external_events_status_check CHECK (status IN ('scheduled', 'postponed', 'cancelled', 'completed')),
  CONSTRAINT aitickets_external_events_end_date_check CHECK (end_date IS NULL OR end_date >= event_date),
  CONSTRAINT aitickets_external_events_capacity_check CHECK (capacity IS NULL OR capacity > 0),
  CONSTRAINT aitickets_external_events_prices_check CHECK (
    (price_min IS NULL OR price_min >= 0) AND (price_max IS NULL OR price_max >= 0)
    AND (price_min IS NULL OR price_max IS NULL OR price_min <= price_max)
  ),
  CONSTRAINT aitickets_external_events_sold_pct_check CHECK (sold_pct IS NULL OR (sold_pct >= 0 AND sold_pct <= 100)),
  CONSTRAINT aitickets_external_events_attendance_check CHECK (attendance IS NULL OR attendance >= 0)
);

CREATE UNIQUE INDEX IF NOT EXISTS aitickets_external_events_source_external_id_key
  ON public.aitickets_external_events (source, external_id) WHERE external_id IS NOT NULL;
CREATE INDEX IF NOT EXISTS aitickets_external_events_event_date_idx ON public.aitickets_external_events (event_date);
CREATE INDEX IF NOT EXISTS aitickets_external_events_type_date_idx ON public.aitickets_external_events (event_type, event_date);
CREATE INDEX IF NOT EXISTS aitickets_external_events_city_date_idx ON public.aitickets_external_events (city_key, event_date);
CREATE INDEX IF NOT EXISTS aitickets_external_events_organizer_idx ON public.aitickets_external_events (organizer_key);
CREATE INDEX IF NOT EXISTS aitickets_external_events_organization_idx ON public.aitickets_external_events (organization_id) WHERE organization_id IS NOT NULL;
CREATE INDEX IF NOT EXISTS aitickets_external_events_lead_idx ON public.aitickets_external_events (lead_id) WHERE lead_id IS NOT NULL;

ALTER TABLE public.aitickets_external_events ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON TABLE public.aitickets_external_events FROM PUBLIC, anon, authenticated;
REVOKE ALL ON SEQUENCE public.aitickets_external_events_id_seq FROM PUBLIC, anon, authenticated;
GRANT USAGE, SELECT ON SEQUENCE public.aitickets_external_events_id_seq TO service_role;

-- Calendario de mercado: fechas especiales que el modelo no puede calcular solo (interferiados, feriados regionales,
-- vacaciones escolares, elecciones, mega eventos, temporadas altas o bajas). Los feriados nacionales los calcula el código
-- (src/lib/market/calendar.ts); kind = 'no_holiday' anula uno calculado.
CREATE TABLE IF NOT EXISTS public.aitickets_market_calendar (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  kind text NOT NULL,
  label text NOT NULL,
  date_from date NOT NULL,
  date_to date NOT NULL,
  -- Alcance: NULL = todo Chile / todas las ciudades / todos los tipos de evento
  region text,
  city_key text,
  event_types text[],
  -- Multiplicador sobre la nota de la fecha (0.1 a 2). NULL = el de su tipo (kind)
  impact numeric(4, 2),
  notes text,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT aitickets_market_calendar_kind_check CHECK (
    kind IN ('holiday', 'bridge_holiday', 'no_holiday', 'school_vacation', 'election', 'mega_event', 'high_demand', 'low_demand', 'blackout', 'other')
  ),
  CONSTRAINT aitickets_market_calendar_dates_check CHECK (date_to >= date_from),
  CONSTRAINT aitickets_market_calendar_impact_check CHECK (impact IS NULL OR (impact >= 0.1 AND impact <= 2))
);

CREATE INDEX IF NOT EXISTS aitickets_market_calendar_dates_idx ON public.aitickets_market_calendar (date_from, date_to);

ALTER TABLE public.aitickets_market_calendar ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON TABLE public.aitickets_market_calendar FROM PUBLIC, anon, authenticated;
REVOKE ALL ON SEQUENCE public.aitickets_market_calendar_id_seq FROM PUBLIC, anon, authenticated;
GRANT USAGE, SELECT ON SEQUENCE public.aitickets_market_calendar_id_seq TO service_role;
