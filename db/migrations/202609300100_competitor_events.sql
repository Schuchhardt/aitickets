-- Leads desde Passline (SOLO resultados de buscador, nunca se visita passline.com: ver docs/runbooks/passline-leads.md).
-- Idempotente. Solo crea/modifica objetos public.aitickets_* (proyecto Supabase compartido).
-- RLS activado SIN políticas + REVOKE ALL a anon/authenticated (tablas, secuencias y funciones) => solo la service role.

-- 1. Eventos vistos en una ticketera de la competencia (una fila por URL de evento).
CREATE TABLE IF NOT EXISTS public.aitickets_competitor_events (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  platform text NOT NULL DEFAULT 'passline',
  url text NOT NULL UNIQUE,
  title text,
  venue text,
  city text,
  region text,
  event_date date,
  category text,
  producer_name text,
  -- Id numérico del productor en la ticketera (solo del archivo semilla passline_rm.json).
  producer_ref text,
  snippet text,
  -- 'search' (resultado de buscador) | 'seed' (archivo local importado a mano).
  seen_via text NOT NULL DEFAULT 'search',
  lead_id uuid REFERENCES public.aitickets_leads(id) ON DELETE SET NULL,
  first_seen_at timestamptz NOT NULL DEFAULT now(),
  last_seen_at timestamptz NOT NULL DEFAULT now(),
  times_seen int NOT NULL DEFAULT 1
);
CREATE INDEX IF NOT EXISTS aitickets_competitor_events_lead_idx
  ON public.aitickets_competitor_events (lead_id) WHERE lead_id IS NOT NULL;
CREATE INDEX IF NOT EXISTS aitickets_competitor_events_platform_seen_idx
  ON public.aitickets_competitor_events (platform, last_seen_at DESC);
CREATE INDEX IF NOT EXISTS aitickets_competitor_events_event_date_idx
  ON public.aitickets_competitor_events (event_date);
CREATE INDEX IF NOT EXISTS aitickets_competitor_events_producer_idx
  ON public.aitickets_competitor_events (lower(producer_name)) WHERE producer_name IS NOT NULL;
ALTER TABLE public.aitickets_competitor_events ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON TABLE public.aitickets_competitor_events FROM PUBLIC, anon, authenticated;
GRANT SELECT, INSERT, UPDATE, DELETE ON TABLE public.aitickets_competitor_events TO service_role;
REVOKE ALL ON SEQUENCE public.aitickets_competitor_events_id_seq FROM PUBLIC, anon, authenticated;
GRANT USAGE, SELECT ON SEQUENCE public.aitickets_competitor_events_id_seq TO service_role;

