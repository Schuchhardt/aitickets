-- 4. Upsert atómico de eventos vistos: inserta o actualiza (times_seen + 1, last_seen_at = now()).
--    Nunca borra datos ya conocidos (coalesce con lo existente primero para producer_name/venue/city).
--    p_rows: [{url, platform?, title?, venue?, city?, region?, event_date?, category?, producer_name?, producer_ref?, snippet?}]
CREATE OR REPLACE FUNCTION public.aitickets_touch_competitor_events(p_rows jsonb, p_seen_via text DEFAULT 'search')
RETURNS TABLE (id bigint, url text, lead_id uuid, inserted boolean)
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
#variable_conflict use_column
BEGIN
  IF jsonb_typeof(p_rows) IS DISTINCT FROM 'array' THEN
    RAISE EXCEPTION 'aitickets_touch_competitor_events: p_rows debe ser un arreglo';
  END IF;
  IF jsonb_array_length(p_rows) > 500 THEN
    RAISE EXCEPTION 'aitickets_touch_competitor_events: máximo 500 filas por llamada';
  END IF;
  RETURN QUERY
  INSERT INTO public.aitickets_competitor_events AS t
    (platform, url, title, venue, city, region, event_date, category, producer_name, producer_ref, snippet, seen_via)
  SELECT DISTINCT ON (r->>'url')
    coalesce(nullif(r->>'platform', ''), 'passline'),
    r->>'url',
    left(nullif(r->>'title', ''), 300),
    left(nullif(r->>'venue', ''), 200),
    left(nullif(r->>'city', ''), 100),
    left(nullif(r->>'region', ''), 100),
    CASE WHEN r->>'event_date' ~ '^\d{4}-\d{2}-\d{2}$' THEN (r->>'event_date')::date END,
    left(nullif(r->>'category', ''), 50),
    left(nullif(r->>'producer_name', ''), 200),
    left(nullif(r->>'producer_ref', ''), 50),
    left(nullif(r->>'snippet', ''), 1000),
    coalesce(nullif(p_seen_via, ''), 'search')
  FROM jsonb_array_elements(p_rows) AS r
  WHERE coalesce(r->>'url', '') <> ''
  ON CONFLICT ON CONSTRAINT aitickets_competitor_events_url_key DO UPDATE SET
    title = coalesce(EXCLUDED.title, t.title),
    venue = coalesce(t.venue, EXCLUDED.venue),
    city = coalesce(t.city, EXCLUDED.city),
    region = coalesce(t.region, EXCLUDED.region),
    event_date = coalesce(EXCLUDED.event_date, t.event_date),
    category = coalesce(t.category, EXCLUDED.category),
    producer_name = coalesce(t.producer_name, EXCLUDED.producer_name),
    producer_ref = coalesce(t.producer_ref, EXCLUDED.producer_ref),
    snippet = coalesce(EXCLUDED.snippet, t.snippet),
    seen_via = CASE WHEN EXCLUDED.seen_via = 'search' THEN 'search' ELSE t.seen_via END,
    last_seen_at = now(),
    times_seen = t.times_seen + 1
  RETURNING t.id, t.url, t.lead_id, (t.xmax = 0) AS inserted;
END;
$$;
REVOKE EXECUTE ON FUNCTION public.aitickets_touch_competitor_events(jsonb, text) FROM PUBLIC, anon, authenticated;
GRANT EXECUTE ON FUNCTION public.aitickets_touch_competitor_events(jsonb, text) TO service_role;

-- 5. El lote de envíos automáticos nunca toma leads de seguimiento manual (defensa adicional al filtro de la app).
CREATE OR REPLACE FUNCTION public.aitickets_claim_outreach_batch(p_limit int)
RETURNS SETOF public.aitickets_leads
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
BEGIN
  RETURN QUERY
  WITH due AS (
    SELECT l.id
    FROM public.aitickets_leads l
    WHERE l.status IN ('enriched', 'contacted')
      AND l.email IS NOT NULL
      AND NOT l.manual_only
      AND l.next_action_at IS NOT NULL
      AND l.next_action_at <= now()
    ORDER BY l.sequence_step ASC, l.score DESC NULLS LAST, l.next_action_at ASC
    LIMIT greatest(0, least(coalesce(p_limit, 0), 100))
    FOR UPDATE SKIP LOCKED
  )
  UPDATE public.aitickets_leads t
     SET next_action_at = now() + interval '30 minutes',
         updated_at = now()
    FROM due
   WHERE t.id = due.id
  RETURNING t.*;
END;
$$;
REVOKE EXECUTE ON FUNCTION public.aitickets_claim_outreach_batch(int) FROM PUBLIC, anon, authenticated;
GRANT EXECUTE ON FUNCTION public.aitickets_claim_outreach_batch(int) TO service_role;
