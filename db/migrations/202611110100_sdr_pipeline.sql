-- Pipeline de SDR (prospección manual): columnas nuevas en leads, tabla de touches, tabla de estrategias.
-- Idempotente. Solo crea/modifica objetos public.aitickets_* (proyecto Supabase compartido).
-- Todas las tablas: RLS activado SIN políticas + REVOKE ALL a anon/authenticated => solo la service role.

-- ============================================================================
-- 1. Columnas nuevas en aitickets_leads
-- ============================================================================

ALTER TABLE public.aitickets_leads ADD COLUMN IF NOT EXISTS niche text;
ALTER TABLE public.aitickets_leads ADD COLUMN IF NOT EXISTS potential text;
ALTER TABLE public.aitickets_leads ADD COLUMN IF NOT EXISTS potential_score int;
ALTER TABLE public.aitickets_leads ADD COLUMN IF NOT EXISTS potential_reason text;
ALTER TABLE public.aitickets_leads ADD COLUMN IF NOT EXISTS next_action text;
ALTER TABLE public.aitickets_leads ADD COLUMN IF NOT EXISTS lost_reason text;
ALTER TABLE public.aitickets_leads ADD COLUMN IF NOT EXISTS gmail_thread_id text;
ALTER TABLE public.aitickets_leads ADD COLUMN IF NOT EXISTS proposal_event_id bigint;
ALTER TABLE public.aitickets_leads ADD COLUMN IF NOT EXISTS proposal_preview_link_id bigint;
ALTER TABLE public.aitickets_leads ADD COLUMN IF NOT EXISTS proposal_created_at timestamptz;
ALTER TABLE public.aitickets_leads ADD COLUMN IF NOT EXISTS discovered_event jsonb;

-- CHECK constraints (DO blocks para idempotencia)

DO $$
BEGIN
  IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'aitickets_leads_niche_check') THEN
    ALTER TABLE public.aitickets_leads
      ADD CONSTRAINT aitickets_leads_niche_check CHECK (
        niche IS NULL OR niche IN ('stand_up', 'teatro', 'musica_en_vivo', 'fiestas', 'clubs', 'talleres', 'seminarios', 'academias', 'otro')
      );
  END IF;
END
$$;

DO $$
BEGIN
  IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'aitickets_leads_potential_check') THEN
    ALTER TABLE public.aitickets_leads
      ADD CONSTRAINT aitickets_leads_potential_check CHECK (
        potential IS NULL OR potential IN ('low', 'medium', 'high')
      );
  END IF;
END
$$;

DO $$
BEGIN
  IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'aitickets_leads_potential_score_check') THEN
    ALTER TABLE public.aitickets_leads
      ADD CONSTRAINT aitickets_leads_potential_score_check CHECK (
        potential_score IS NULL OR (potential_score >= 0 AND potential_score <= 100)
      );
  END IF;
END
$$;

DO $$
BEGIN
  IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'aitickets_leads_next_action_check') THEN
    ALTER TABLE public.aitickets_leads
      ADD CONSTRAINT aitickets_leads_next_action_check CHECK (
        next_action IS NULL OR next_action IN ('draft_t1', 'draft_t2', 'draft_t3', 'mark_lost', 'reply', 'proposal', 'none')
      );
  END IF;
END
$$;

DO $$
BEGIN
  IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'aitickets_leads_lost_reason_check') THEN
    ALTER TABLE public.aitickets_leads
      ADD CONSTRAINT aitickets_leads_lost_reason_check CHECK (
        lost_reason IS NULL OR lost_reason IN ('no_reply', 'not_interested', 'bounced', 'bad_fit', 'locked_in_competitor', 'other')
      );
  END IF;
END
$$;

-- Índices

CREATE INDEX IF NOT EXISTS aitickets_leads_niche_idx
  ON public.aitickets_leads (niche) WHERE niche IS NOT NULL;

CREATE INDEX IF NOT EXISTS aitickets_leads_next_action_idx
  ON public.aitickets_leads (next_action, next_action_at) WHERE next_action IS NOT NULL;

-- ============================================================================
-- 2. Tabla aitickets_lead_touches (registro de cada paso de la secuencia)
-- ============================================================================

CREATE TABLE IF NOT EXISTS public.aitickets_lead_touches (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  lead_id uuid NOT NULL REFERENCES public.aitickets_leads(id) ON DELETE CASCADE,
  step int,
  kind text NOT NULL CHECK (kind IN ('outreach', 'reply', 'proposal')),
  channel text CHECK (channel IS NULL OR channel IN ('email', 'whatsapp', 'instagram')),
  strategy_slug text,
  cta text,
  subject text,
  gmail_draft_id text,
  gmail_message_id text,
  gmail_thread_id text,
  outcome text NOT NULL DEFAULT 'drafted' CHECK (outcome IN ('drafted', 'sent', 'replied', 'bounced', 'discarded')),
  reply_sentiment text CHECK (reply_sentiment IS NULL OR reply_sentiment IN ('positive', 'neutral', 'negative', 'unsubscribe')),
  drafted_at timestamptz NOT NULL DEFAULT now(),
  sent_at timestamptz,
  reply_at timestamptz,
  created_at timestamptz NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS aitickets_lead_touches_lead_idx
  ON public.aitickets_lead_touches (lead_id, created_at);
CREATE INDEX IF NOT EXISTS aitickets_lead_touches_strategy_idx
  ON public.aitickets_lead_touches (strategy_slug) WHERE strategy_slug IS NOT NULL;
CREATE INDEX IF NOT EXISTS aitickets_lead_touches_outcome_idx
  ON public.aitickets_lead_touches (outcome, sent_at);

ALTER TABLE public.aitickets_lead_touches ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON TABLE public.aitickets_lead_touches FROM PUBLIC, anon, authenticated;

REVOKE ALL ON SEQUENCE public.aitickets_lead_touches_id_seq FROM PUBLIC, anon, authenticated;
GRANT USAGE, SELECT ON SEQUENCE public.aitickets_lead_touches_id_seq TO service_role;

-- ============================================================================
-- 3. Tabla aitickets_lead_strategies (catálogo de ángulos por nicho)
-- ============================================================================

CREATE TABLE IF NOT EXISTS public.aitickets_lead_strategies (
  slug text PRIMARY KEY,
  niche text NOT NULL,
  name text NOT NULL,
  pitch text,
  landing_url text,
  status text NOT NULL DEFAULT 'active' CHECK (status IN ('active', 'paused', 'discarded')),
  notes text,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now()
);

DO $$
BEGIN
  IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'aitickets_lead_strategies_niche_check') THEN
    ALTER TABLE public.aitickets_lead_strategies
      ADD CONSTRAINT aitickets_lead_strategies_niche_check CHECK (
        niche IN ('stand_up', 'teatro', 'musica_en_vivo', 'fiestas', 'clubs', 'talleres', 'seminarios', 'academias', 'otro')
      );
  END IF;
END
$$;

ALTER TABLE public.aitickets_lead_strategies ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON TABLE public.aitickets_lead_strategies FROM PUBLIC, anon, authenticated;

