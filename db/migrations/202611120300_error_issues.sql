-- Bandeja de errores de producción: un registro por issue de Sentry (Sentry ya agrupa los eventos del mismo error
-- en un issue con id estable, así que sentry_issue_id UNIQUE evita duplicados aunque llegue el webhook y el cron a la vez).
-- Lo llenan el webhook /api/webhooks/sentry y la función programada sentry-sync (netlify/lib/sentry-issues.mjs);
-- lo leen list_error_issues / get_error_issue del MCP de administración. El repo es público: nada de esto va a GitHub.
-- Idempotente. Solo toca objetos de AI Tickets.
CREATE TABLE IF NOT EXISTS public.aitickets_error_issues (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  sentry_issue_id text NOT NULL,
  short_id text,
  title text NOT NULL,
  culprit text,
  level text,
  platform text,
  -- Estado en Sentry: unresolved, resolved, ignored
  sentry_status text NOT NULL DEFAULT 'unresolved',
  permalink text,
  first_seen timestamptz,
  last_seen timestamptz,
  event_count integer NOT NULL DEFAULT 0,
  user_count integer NOT NULL DEFAULT 0,
  -- Triage propio: new → in_progress → fixed (con pr_url) o ignored
  triage_status text NOT NULL DEFAULT 'new',
  pr_url text,
  notes text,
  -- Última vez que un issue resuelto volvió a aparecer (vuelve a triage_status = new)
  regressed_at timestamptz,
  -- Aviso a Slack del issue nuevo (se reclama con UPDATE … WHERE notified_at IS NULL: un solo aviso)
  notified_at timestamptz,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT aitickets_error_issues_sentry_issue_id_key UNIQUE (sentry_issue_id),
  CONSTRAINT aitickets_error_issues_triage_status_check CHECK (triage_status IN ('new', 'in_progress', 'fixed', 'ignored'))
);

CREATE INDEX IF NOT EXISTS aitickets_error_issues_triage_last_seen_idx
  ON public.aitickets_error_issues (triage_status, last_seen DESC);

ALTER TABLE public.aitickets_error_issues ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON TABLE public.aitickets_error_issues FROM PUBLIC, anon, authenticated;
